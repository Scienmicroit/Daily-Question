import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const output = new URL('../client.js', import.meta.url)
const result = await build({
  absWorkingDir: fileURLToPath(new URL('../', import.meta.url)),
  entryPoints: ['ui/app.js'],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: 'DailyQuestionClient',
  target: 'es2022',
  charset: 'utf8',
  keepNames: true,
  banner: { js: '// Generated by npm run build:client. Edit ui/ sources.\nwindow.__ModuleLoader__.load({\n  id: "daily-question",\n  factory(require) {' },
  footer: { js: '    return DailyQuestionClient.createClient(require("react"), { window, fetch, styles: typeof styles === "undefined" ? undefined : styles }).plugin\n  },\n})' },
})
const bundle = result.outputFiles[0].text
if (process.argv.includes('--check')) {
  const current = await readFile(output, 'utf8')
  if (current.replaceAll('\r\n', '\n') !== bundle) throw new Error('前端入口需要重新生成，请运行 npm run build:client')
} else {
  await writeFile(output, bundle)
}
